        SELECT v.*, 1 + FLOOR(5 * BITAND(HASH(:SEED, 'KNA1', v.KUNNR, 'M01d'), 4294967295) / 4294967295.0) AS off
        FROM ERP_SOURCE.KNA1 v WHERE v.KUNNR NOT LIKE 'TEST%')
    SELECT KUNNR, NAME1, EMAIL, LAND1, REGIO, KTOKD, KLIMK, ERDAT, TIMESTAMPADD(day, off, LOAD_TS)
    FROM c
    WHERE DATEADD(day, -1, LOAD_TS::DATE) <= DATEADD(day, -5, :l_date) AND TIMESTAMPADD(day, off, LOAD_TS) <= :cap_ts
    QUALIFY ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'KNA1', KUNNR, 'M01'), KUNNR) <= :k;
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'M01', 'KNA1', :base, 0.01, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- ── Messy-load facts and the result ─────────────────────────────────────
    stage := 'stats';
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_STATS (RUN_ID, TARGET_DB, PHASE, NAME, TABLE_NAME, VALUE, DETAIL, PARAMS, LOGGED_AT)
    WITH x AS (
        SELECT 'T001W' AS t, COUNT(*) AS n, TO_VARCHAR(HASH_AGG(*)) AS h FROM WMS_SOURCE.T001W
        UNION ALL SELECT 'LFA1', COUNT(*), TO_VARCHAR(HASH_AGG(*)) FROM SRM_SOURCE.LFA1
        UNION ALL SELECT 'MARA', COUNT(*), TO_VARCHAR(HASH_AGG(*)) FROM SRM_SOURCE.MARA
        UNION ALL SELECT 'KNA1', COUNT(*), TO_VARCHAR(HASH_AGG(*)) FROM ERP_SOURCE.KNA1
        UNION ALL SELECT 'TCURR', COUNT(*), TO_VARCHAR(HASH_AGG(*)) FROM ERP_SOURCE.TCURR
        UNION ALL SELECT 'SOURCING', COUNT(*), TO_VARCHAR(HASH_AGG(*)) FROM SRM_SOURCE.SOURCING
        UNION ALL SELECT 'VBAK', COUNT(*), TO_VARCHAR(HASH_AGG(*)) FROM ERP_SOURCE.VBAK
        UNION ALL SELECT 'VBAP', COUNT(*), TO_VARCHAR(HASH_AGG(*)) FROM ERP_SOURCE.VBAP
        UNION ALL SELECT 'VTTK', COUNT(*), TO_VARCHAR(HASH_AGG(*)) FROM TMS_SOURCE.VTTK
        UNION ALL SELECT 'MARD', COUNT(*), TO_VARCHAR(HASH_AGG(*)) FROM WMS_SOURCE.MARD)
    SELECT :run_id, :TARGET_DB, 'MESSY', 'ROWS', t, n::FLOAT, NULL,
           OBJECT_CONSTRUCT('seed', :SEED, 'end_date', :END_DATE), CURRENT_TIMESTAMP()::TIMESTAMP_NTZ FROM x
    UNION ALL
    SELECT :run_id, :TARGET_DB, 'MESSY', 'CHECKSUM', t, NULL, h,
           OBJECT_CONSTRUCT('seed', :SEED, 'end_date', :END_DATE), CURRENT_TIMESTAMP()::TIMESTAMP_NTZ FROM x;

    SELECT OBJECT_CONSTRUCT(
               'status', 'OK', 'run_id', :run_id, 'target_db', :TARGET_DB,
               'injected', (SELECT OBJECT_AGG(CODE, tables) FROM (
                               SELECT CODE, OBJECT_AGG(TABLE_NAME, TO_VARIANT(AFFECTED_ROWS)) AS tables
                               FROM SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG WHERE RUN_ID = :run_id GROUP BY CODE)),
               'elapsed_s', DATEDIFF(millisecond, :run_t0, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ) / 1000)
      INTO :result;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_LOG (RUN_ID, TARGET_DB, STAGE, TABLE_NAME, CHUNK, ROWS_WRITTEN, STARTED_AT, ENDED_AT)
    SELECT :run_id, :TARGET_DB, 'done', NULL, NULL, NULL, :run_t0, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;
    RETURN result;

EXCEPTION
    WHEN OTHER THEN
        LET err_code VARCHAR := SQLCODE;
        LET err_msg VARCHAR := SQLERRM;
        INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_LOG (RUN_ID, TARGET_DB, STAGE, TABLE_NAME, CHUNK, ROWS_WRITTEN, STARTED_AT, ENDED_AT, PARAMS)
        SELECT COALESCE(:run_id, 'unknown'), :TARGET_DB, 'error', NULL, :stage, NULL, :run_t0, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
               OBJECT_CONSTRUCT('sqlcode', :err_code, 'sqlerrm', :err_msg);
        RETURN OBJECT_CONSTRUCT('status', 'ERROR', 'run_id', run_id, 'stage', stage, 'sqlcode', err_code, 'sqlerrm', err_msg);
END;
$$;
