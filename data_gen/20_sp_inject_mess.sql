-- ============================================================================
-- data_gen/20_sp_inject_mess.sql — OPS.SP_INJECT_MESS: the §4 defects, on top of a clean load
-- Card:       C08 (.agents/tasks/claude/C08_data_generator.md)
-- Spec:       docs/DATA_SPEC.md §4 (mess catalogue), §3.8 (LOAD_TS cap), §6
-- Role:       ACCOUNTADMIN        Warehouse: FORGE_WH (XS) at SF <= 1
-- Run order:  3 of 5 (00 → 10 → 20 → 30 → 99). Re-runnable: CREATE OR REPLACE.
-- Parameters: TARGET_DB, SEED (the same as the generator's), END_DATE (the same).
-- Expected:   CREATE succeeds. A CALL right after SP_GENERATE_DATA returns
--             {"status": "OK", "injected": {"M01": {"VBAK": n, ...}, ..., "E12": {...}}}.
--             It refuses to run twice on the same load (test customers already present):
--             run SP_GENERATE_DATA first.
--
-- Picks are exact: k = ROUND(rate × base) rows, the k with the lowest
-- HASH(SEED, '<TABLE>', <key>, '<CODE>'), so rates hold even at SF 0.01 and every run
-- picks the same rows. Order of injection (so copies stay identical and no LOAD_TS passes
-- END_DATE 05:00): M04 → E03, E01, E02, E04–E06, E08, E07a–c, E09, E11, E12 → M06 → M02
-- → M03 → M07 → M01. M05 (currencies) is set by the generator, not injected.
-- Deviation (reported in HANDOFF): M07 on VTTK.VBELN uses lower case, because a trailing
-- space doesn't fit VARCHAR(12) on 12-character order IDs. UPPER(TRIM()) repairs both.
-- ============================================================================

CREATE OR REPLACE PROCEDURE SUPPLY_CHAIN_FORGE.OPS.SP_INJECT_MESS(
    TARGET_DB VARCHAR, SEED NUMBER, END_DATE DATE)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS CALLER
COMMENT = 'C08: injects the DATA_SPEC §4 defects and edge cases into a clean load, with exact, hash-picked counts.'
AS
$$
DECLARE
    stage     VARCHAR DEFAULT 'start';
    run_id    VARCHAR;
    ok_name   BOOLEAN;
    s_date    DATE;
    l_date    DATE;
    cap_ts    TIMESTAMP_NTZ;      -- no LOAD_TS may be later than END_DATE 05:00 (§3.8)
    base      INTEGER;
    k         INTEGER;
    n         INTEGER;
    run_t0    TIMESTAMP_NTZ;
    result    VARIANT;
BEGIN
    SELECT UUID_STRING(), CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
           COALESCE(REGEXP_LIKE(:TARGET_DB, '^[A-Za-z_][A-Za-z0-9_$]*$'), FALSE)
      INTO :run_id, :run_t0, :ok_name;
    IF (NOT ok_name OR SEED IS NULL OR END_DATE IS NULL) THEN
        RETURN OBJECT_CONSTRUCT('status', 'ERROR', 'stage', 'parameters',
            'sqlerrm', 'TARGET_DB must be a plain identifier; SEED and END_DATE required');
    END IF;
    EXECUTE IMMEDIATE 'USE SCHEMA ' || :TARGET_DB || '.OPS';
    SELECT DATEADD(year, -10, :END_DATE), DATEADD(day, -1, :END_DATE), TIMESTAMPADD(hour, 5, :END_DATE::TIMESTAMP_NTZ)
      INTO :s_date, :l_date, :cap_ts;

    stage := 'guard';
    SELECT COUNT(*) INTO :n FROM ERP_SOURCE.KNA1 WHERE KUNNR LIKE 'TEST%';
    IF (n > 0) THEN
        RETURN OBJECT_CONSTRUCT('status', 'ERROR', 'stage', 'guard',
            'sqlerrm', 'This load already has injected defects. Run SP_GENERATE_DATA first, then SP_INJECT_MESS once.');
    END IF;

    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_LOG (RUN_ID, TARGET_DB, STAGE, TABLE_NAME, CHUNK, ROWS_WRITTEN, STARTED_AT, ENDED_AT, PARAMS)
    SELECT :run_id, :TARGET_DB, 'start', NULL, NULL, NULL, :run_t0, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
           OBJECT_CONSTRUCT('procedure', 'SP_INJECT_MESS', 'seed', :SEED, 'end_date', :END_DATE);

    -- Daily FX lookup (latest rate on or before each day), for E08's USD threshold.
    CREATE OR REPLACE TEMPORARY TABLE TMP_FX AS
    WITH cal AS (SELECT DATEADD(day, (ROW_NUMBER() OVER (ORDER BY SEQ8()) - 1)::INT, DATEADD(day, -7, :s_date)) AS d
                 FROM TABLE(GENERATOR(ROWCOUNT => 3700))),
    cur AS (SELECT DISTINCT FCURR AS CUR FROM ERP_SOURCE.TCURR),
    grid AS (SELECT c.CUR, cal.d, t.UKURS FROM cal CROSS JOIN cur c
             LEFT JOIN ERP_SOURCE.TCURR t ON t.FCURR = c.CUR AND t.GDATU = cal.d AND t.KURST = 'M' AND t.TCURR = 'USD')
    SELECT CUR, d, LAST_VALUE(UKURS IGNORE NULLS) OVER (PARTITION BY CUR ORDER BY d ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS rate
    FROM grid
    UNION ALL SELECT 'USD', d, 1 FROM cal;

    -- ── M04 test / dummy records ────────────────────────────────────────────
    stage := 'M04';
    INSERT INTO ERP_SOURCE.KNA1 (KUNNR, NAME1, EMAIL, LAND1, REGIO, KTOKD, KLIMK, ERDAT, LOAD_TS)
    SELECT 'TEST' || LPAD(i, 4, '0'), CASE WHEN i = 5 THEN 'DUMMY ACCOUNT' ELSE 'TEST CUSTOMER ' || i END,
           'test' || i || '@example.com', 'USA', 'AMER', 'SMB', 1000, :s_date,
           TIMESTAMPADD(minute, 120, DATEADD(day, 1, :s_date)::TIMESTAMP_NTZ)
    FROM (SELECT ROW_NUMBER() OVER (ORDER BY SEQ8()) AS i FROM TABLE(GENERATOR(ROWCOUNT => 5)));
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'M04', 'KNA1', 5, 1.0, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    SELECT COUNT(*) INTO :base FROM ERP_SOURCE.VBAK;
    k := ROUND(base * 0.003);
    UPDATE ERP_SOURCE.VBAK t SET KUNNR = p.new_kunnr
    FROM (SELECT VBELN,
                 'TEST' || LPAD(1 + MOD(ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'VBAK', VBELN, 'M04'), VBELN) - 1, 5), 4, '0') AS new_kunnr
          FROM ERP_SOURCE.VBAK
          QUALIFY ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'VBAK', VBELN, 'M04'), VBELN) <= :k) p
    WHERE t.VBELN = p.VBELN;
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'M04', 'VBAK', :base, 0.003, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    INSERT INTO SRM_SOURCE.LFA1 (LIFNR, NAME1, LAND1, REGIO, SUPP_TIER, LEAD_TM_DAYS, RELIAB_SCR, ZTERM, EMAIL, ERDAT, LOAD_TS)
    SELECT 'TESTV' || LPAD(i, 3, '0'), 'TEST VENDOR ' || i, 'USA', 'AMER', 3, 30, 0.70, 'NET30',
           'vendor' || i || '@example.com', :s_date, TIMESTAMPADD(minute, 120, DATEADD(day, 1, :s_date)::TIMESTAMP_NTZ)
    FROM (SELECT ROW_NUMBER() OVER (ORDER BY SEQ8()) AS i FROM TABLE(GENERATOR(ROWCOUNT => 2)));
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'M04', 'LFA1', 2, 1.0, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    INSERT INTO SRM_SOURCE.SOURCING (SOURCE_ID, LIFNR, MATNR, IS_PRIMARY, CONTRACT_PRICE, WAERS, VDATU, BDATU, LOAD_TS)
    SELECT 'SRC99000' || i, 'TESTV' || LPAD(i, 3, '0'), m.MATNR, FALSE, 1.00, 'USD', :s_date, NULL,
           TIMESTAMPADD(minute, 120, DATEADD(day, 1, :s_date)::TIMESTAMP_NTZ)
    FROM (SELECT ROW_NUMBER() OVER (ORDER BY SEQ8()) AS i FROM TABLE(GENERATOR(ROWCOUNT => 2))) g
    JOIN (SELECT MATNR, ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'SOURCING', MATNR, 'M04'), MATNR) AS r
          FROM SRM_SOURCE.MARA) m ON m.r = g.i;
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'M04', 'SOURCING', 2, 1.0, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    INSERT INTO SRM_SOURCE.MARA (MATNR, MAKTX, MATKL, SUBCAT, STPRS, BRGEW, CRIT_FLG, LOAD_TS)
    SELECT 'MAT99990' || i, 'DO NOT USE - TEST PART', 'FASTENERS', 'SCREWS', 0.01, 0.001, FALSE,
           TIMESTAMPADD(minute, 120, DATEADD(day, 1, :s_date)::TIMESTAMP_NTZ)
    FROM (SELECT ROW_NUMBER() OVER (ORDER BY SEQ8()) AS i FROM TABLE(GENERATOR(ROWCOUNT => 4)));
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'M04', 'MARA', 4, 1.0, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    SELECT COUNT(*) INTO :base FROM ERP_SOURCE.VBAP;
    k := ROUND(base * 0.001);
    UPDATE ERP_SOURCE.VBAP t SET MATNR = p.new_matnr
    FROM (SELECT LINE_ID,
                 'MAT99990' || (1 + MOD(ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'VBAP', LINE_ID, 'M04'), LINE_ID) - 1, 4)) AS new_matnr
          FROM ERP_SOURCE.VBAP
          QUALIFY ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'VBAP', LINE_ID, 'M04'), LINE_ID) <= :k) p
    WHERE t.LINE_ID = p.LINE_ID;
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'M04', 'VBAP', :base, 0.001, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- ── E03 return orders (1.5% of orders; 60% of them with a return shipment) ─
    stage := 'E03';
    SELECT COUNT(*) INTO :base FROM ERP_SOURCE.VBAK;
    k := ROUND(base * 0.015);
    UPDATE ERP_SOURCE.VBAK t SET AUART = 'RE'
    FROM (SELECT VBELN FROM ERP_SOURCE.VBAK
          QUALIFY ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'VBAK', VBELN, 'E03'), VBELN) <= :k) p
    WHERE t.VBELN = p.VBELN;
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'E03', 'VBAK', :base, 0.015, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- Keep a shipment on 60% of the returns: remove the shipments of the excess.
    SELECT COUNT(*) INTO :base FROM ERP_SOURCE.VBAK WHERE AUART = 'RE';
    SELECT GREATEST(0, COUNT(DISTINCT o.VBELN) - ROUND(:base * 0.60)) INTO :k
    FROM ERP_SOURCE.VBAK o JOIN TMS_SOURCE.VTTK s ON s.VBELN = o.VBELN WHERE o.AUART = 'RE';
    DELETE FROM TMS_SOURCE.VTTK t
    USING (SELECT o.VBELN FROM ERP_SOURCE.VBAK o
           WHERE o.AUART = 'RE' AND EXISTS (SELECT 1 FROM TMS_SOURCE.VTTK s WHERE s.VBELN = o.VBELN)
           QUALIFY ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'VBAK', o.VBELN, 'E03ship'), o.VBELN) <= :k) p
    WHERE t.VBELN = p.VBELN;
    SELECT COUNT(DISTINCT o.VBELN) INTO :n
    FROM ERP_SOURCE.VBAK o JOIN TMS_SOURCE.VTTK s ON s.VBELN = o.VBELN WHERE o.AUART = 'RE';
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'E03', 'VTTK_SHARE', :base, 0.60, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- ── E01 missing promised date (0.8% of delivered shipments) ─────────────
    stage := 'E01';
    SELECT COUNT(*) INTO :base FROM TMS_SOURCE.VTTK WHERE ACT_DLV_DT IS NOT NULL;
    k := ROUND(base * 0.008);
    UPDATE TMS_SOURCE.VTTK t SET PROM_DLV_DT = NULL
    FROM (SELECT TKNUM FROM TMS_SOURCE.VTTK WHERE ACT_DLV_DT IS NOT NULL
          QUALIFY ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'VTTK', TKNUM, 'E01'), TKNUM) <= :k) p
    WHERE t.TKNUM = p.TKNUM;
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'E01', 'VTTK', :base, 0.008, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- ── E02 cancelled after shipping (0.5% of DELIVERED orders) ─────────────
    stage := 'E02';
    SELECT COUNT(*) INTO :base FROM ERP_SOURCE.VBAK WHERE GBSTK = 'DELIVERED' AND AUART = 'OR';
    k := ROUND(base * 0.005);
    UPDATE ERP_SOURCE.VBAK t SET GBSTK = 'CANCELLED'
    FROM (SELECT VBELN FROM ERP_SOURCE.VBAK WHERE GBSTK = 'DELIVERED' AND AUART = 'OR'
          QUALIFY ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'VBAK', VBELN, 'E02'), VBELN) <= :k) p
    WHERE t.VBELN = p.VBELN;
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'E02', 'VBAK', :base, 0.005, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- ── E04 over-shipment (1% of shipped lines) ─────────────────────────────
    stage := 'E04';
    SELECT COUNT(*) INTO :base FROM ERP_SOURCE.VBAP WHERE QTY_SHIPPED > 0;
    k := ROUND(base * 0.01);
    UPDATE ERP_SOURCE.VBAP t
       SET QTY_SHIPPED = ROUND(t.KWMENG * (1.05 + 0.15 * BITAND(HASH(:SEED, 'VBAP', t.LINE_ID, 'E04q'), 4294967295) / 4294967295.0))
    FROM (SELECT LINE_ID FROM ERP_SOURCE.VBAP WHERE QTY_SHIPPED > 0
          QUALIFY ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'VBAP', LINE_ID, 'E04'), LINE_ID) <= :k) p
    WHERE t.LINE_ID = p.LINE_ID;
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'E04', 'VBAP', :base, 0.01, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- ── E06 zero daily usage (2% of stocked pairs, all their snapshots) ─────
    stage := 'E06';
    SELECT COUNT(*) INTO :base FROM (SELECT DISTINCT WERKS, MATNR FROM WMS_SOURCE.MARD);
    k := ROUND(base * 0.02);
    UPDATE WMS_SOURCE.MARD t
       SET DAILY_USG = 0, REORD_PT = 0,
           LABST = 50 + FLOOR(451 * BITAND(HASH(:SEED, 'MARD', t.INV_KEY, 'E06q'), 4294967295) / 4294967295.0)
    FROM (SELECT WERKS, MATNR FROM (SELECT DISTINCT WERKS, MATNR FROM WMS_SOURCE.MARD)
          QUALIFY ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'MARD', WERKS || '-' || MATNR, 'E06'), WERKS, MATNR) <= :k) p
    WHERE t.WERKS = p.WERKS AND t.MATNR = p.MATNR;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'E06', 'MARD_PAIRS', :base, 0.02, :k, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- ── E05 negative on-hand (0.3% of snapshot rows) ────────────────────────
    stage := 'E05';
    SELECT COUNT(*) INTO :base FROM WMS_SOURCE.MARD;
    k := ROUND(base * 0.003);
    UPDATE WMS_SOURCE.MARD t
       SET LABST = -(1 + FLOOR(50 * BITAND(HASH(:SEED, 'MARD', t.INV_KEY, 'E05q'), 4294967295) / 4294967295.0))
    FROM (SELECT INV_KEY FROM WMS_SOURCE.MARD
          QUALIFY ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'MARD', INV_KEY, 'E05'), INV_KEY) <= :k) p
    WHERE t.INV_KEY = p.INV_KEY;
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'E05', 'MARD', :base, 0.003, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- ── E08 cost outliers (0.1% of shipments, among those with freight ≥ USD 300) ─
    stage := 'E08';
    SELECT COUNT(*) INTO :base FROM TMS_SOURCE.VTTK;
    k := ROUND(base * 0.001);
    UPDATE TMS_SOURCE.VTTK t SET FREIGHT_AMT = t.FREIGHT_AMT * 100
    FROM (SELECT s.TKNUM FROM TMS_SOURCE.VTTK s JOIN TMP_FX fx ON fx.CUR = s.WAERS AND fx.d = s.DPTBG
          WHERE s.FREIGHT_AMT * fx.rate >= 300
          QUALIFY ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'VTTK', s.TKNUM, 'E08'), s.TKNUM) <= :k) p
    WHERE t.TKNUM = p.TKNUM;
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'E08', 'VTTK', :base, 0.001, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- ── E07a/b/c NULL duty (60% of domestic), handling (1%), freight (0.2%) ─
    stage := 'E07';
    SELECT COUNT(*) INTO :base
    FROM TMS_SOURCE.VTTK s JOIN ERP_SOURCE.VBAK o ON o.VBELN = s.VBELN
    JOIN ERP_SOURCE.KNA1 c ON c.KUNNR = o.KUNNR JOIN WMS_SOURCE.T001W pl ON pl.WERKS = s.WERKS
    WHERE pl.LAND1 = c.LAND1;
    k := ROUND(base * 0.60);
    UPDATE TMS_SOURCE.VTTK t SET DUTY_AMT = NULL
    FROM (SELECT s.TKNUM FROM TMS_SOURCE.VTTK s JOIN ERP_SOURCE.VBAK o ON o.VBELN = s.VBELN
          JOIN ERP_SOURCE.KNA1 c ON c.KUNNR = o.KUNNR JOIN WMS_SOURCE.T001W pl ON pl.WERKS = s.WERKS
          WHERE pl.LAND1 = c.LAND1
          QUALIFY ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'VTTK', s.TKNUM, 'E07a'), s.TKNUM) <= :k) p
    WHERE t.TKNUM = p.TKNUM;
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'E07a', 'VTTK', :base, 0.60, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    SELECT COUNT(*) INTO :base FROM TMS_SOURCE.VTTK;
    k := ROUND(base * 0.01);
    UPDATE TMS_SOURCE.VTTK t SET HANDLING_AMT = NULL
    FROM (SELECT TKNUM FROM TMS_SOURCE.VTTK
          QUALIFY ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'VTTK', TKNUM, 'E07b'), TKNUM) <= :k) p
    WHERE t.TKNUM = p.TKNUM;
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'E07b', 'VTTK', :base, 0.01, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    k := ROUND(base * 0.002);
    UPDATE TMS_SOURCE.VTTK t SET FREIGHT_AMT = NULL
    FROM (SELECT TKNUM FROM TMS_SOURCE.VTTK
          QUALIFY ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'VTTK', TKNUM, 'E07c'), TKNUM) <= :k) p
    WHERE t.TKNUM = p.TKNUM;
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'E07c', 'VTTK', :base, 0.002, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- ── E09a/b orphan lines and shipments (0.2% each): an order that doesn't exist ─
    stage := 'E09';
    SELECT COUNT(*) INTO :base FROM ERP_SOURCE.VBAP;
    k := ROUND(base * 0.002);
    UPDATE ERP_SOURCE.VBAP t SET VBELN = p.new_vbeln
    FROM (SELECT LINE_ID, 'ORD9' || LPAD(ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'VBAP', LINE_ID, 'E09a'), LINE_ID), 8, '0') AS new_vbeln
          FROM ERP_SOURCE.VBAP
          QUALIFY ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'VBAP', LINE_ID, 'E09a'), LINE_ID) <= :k) p
    WHERE t.LINE_ID = p.LINE_ID;
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'E09a', 'VBAP', :base, 0.002, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    SELECT COUNT(*) INTO :base FROM TMS_SOURCE.VTTK;
    k := ROUND(base * 0.002);
    UPDATE TMS_SOURCE.VTTK t SET VBELN = p.new_vbeln
    FROM (SELECT TKNUM, 'ORD9' || LPAD(50000000 + ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'VTTK', TKNUM, 'E09b'), TKNUM), 8, '0') AS new_vbeln
          FROM TMS_SOURCE.VTTK
          QUALIFY ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'VTTK', TKNUM, 'E09b'), TKNUM) <= :k) p
    WHERE t.TKNUM = p.TKNUM;
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'E09b', 'VTTK', :base, 0.002, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- ── E11 two valid primaries (1% of parts): a second, later primary row ───
    stage := 'E11';
    SELECT COUNT(*) INTO :base FROM SRM_SOURCE.MARA WHERE MATNR NOT LIKE 'MAT9999%';
    k := ROUND(base * 0.01);
    INSERT INTO SRM_SOURCE.SOURCING (SOURCE_ID, LIFNR, MATNR, IS_PRIMARY, CONTRACT_PRICE, WAERS, VDATU, BDATU, LOAD_TS)
    WITH cur AS (   -- the primary valid today, per part
        SELECT s.* FROM SRM_SOURCE.SOURCING s
        WHERE s.IS_PRIMARY AND s.BDATU IS NULL AND s.MATNR NOT LIKE 'MAT9999%'
        QUALIFY ROW_NUMBER() OVER (PARTITION BY s.MATNR ORDER BY s.VDATU DESC, s.SOURCE_ID) = 1),
    pick AS (
        SELECT cur.*, ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'SOURCING', cur.MATNR, 'E11'), cur.MATNR) AS r
        FROM cur QUALIFY r <= :k),
    d AS (
        SELECT pick.*,
               LEAST(DATEADD(day, -1, :l_date),
                     DATEADD(day, (30 + FLOOR(335 * BITAND(HASH(:SEED, 'SOURCING', pick.MATNR, 'E11d'), 4294967295) / 4294967295.0))::INT,
                             pick.VDATU)) AS new_vdatu
        FROM pick)
    SELECT 'SRC9' || LPAD(d.r, 5, '0'),
           'SUP' || LPAD(1 + MOD(SUBSTR(d.LIFNR, 4)::NUMBER + 36, 150), 5, '0'),
           d.MATNR, TRUE, d.CONTRACT_PRICE, d.WAERS, d.new_vdatu, NULL,
           TIMESTAMPADD(minute, 120, DATEADD(day, 1, d.new_vdatu)::TIMESTAMP_NTZ)
    FROM d;
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'E11', 'SOURCING', :base, 0.01, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- ── E12 future-dated orders (0.02% of orders, among those without shipments) ─
    stage := 'E12';
    SELECT COUNT(*) INTO :base FROM ERP_SOURCE.VBAK;
    k := ROUND(base * 0.0002);
    UPDATE ERP_SOURCE.VBAK t
       SET AUDAT = DATEADD(day, (1 + FLOOR(400 * BITAND(HASH(:SEED, 'VBAK', t.VBELN, 'E12d'), 4294967295) / 4294967295.0))::INT,
                           t.LOAD_TS::DATE)
    FROM (SELECT o.VBELN FROM ERP_SOURCE.VBAK o
          WHERE o.AUART = 'OR' AND NOT EXISTS (SELECT 1 FROM TMS_SOURCE.VTTK s WHERE s.VBELN = o.VBELN)
          QUALIFY ROW_NUMBER() OVER (ORDER BY HASH(:SEED, 'VBAK', o.VBELN, 'E12'), o.VBELN) <= :k) p
    WHERE t.VBELN = p.VBELN;
    n := SQLROWCOUNT;
    INSERT INTO SUPPLY_CHAIN_FORGE.OPS.GEN_MESS_LOG SELECT :run_id, :TARGET_DB, 'E12', 'VBAK', :base, 0.0002, :n, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

    -- ── M06 late-arriving rows (1% of VBAP and VTTK rows at least 30 days old) ─
    -- The business date is LOAD_TS's day minus one (§3.8), before any shift.
    stage := 'M06';
    SELECT COUNT(*) INTO :base FROM ERP_SOURCE.VBAP WHERE DATEADD(day, -1, LOAD_TS::DATE) <= DATEADD(day, -30, :l_date);
    k := ROUND(base * 0.01);
